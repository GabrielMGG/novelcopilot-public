CREATE TABLE ai_generation_usage (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    user_id CHAR(36) NOT NULL,
    story_id INT,
    chapter_id INT,
    action VARCHAR(50) NOT NULL,
    provider VARCHAR(50) NOT NULL,
    model VARCHAR(100) NOT NULL,
    fallback_used BOOLEAN DEFAULT FALSE,
    input_tokens INT,
    cached_input_tokens INT,
    output_tokens INT,
    total_tokens INT,
    provider_reported_cost_usd DECIMAL(18,10),
    calculated_cost_usd DECIMAL(18,10),
    effective_cost_usd DECIMAL(18,10),
    cost_source VARCHAR(50),
    duration_ms BIGINT,
    status VARCHAR(50),
    error_code VARCHAR(255),
    context_truncated BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    idempotency_key VARCHAR(100),
    UNIQUE KEY uk_user_idempotency (user_id, idempotency_key)
);
